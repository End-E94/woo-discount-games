<?php
/**
 * Coupon generation.
 *
 * @package WooDiscountGames
 */

defined( 'ABSPATH' ) || exit;

/**
 * Creates single-use WooCommerce coupons for winners.
 */
class WDGames_Coupon {

	/**
	 * Creates a coupon from the saved settings.
	 *
	 * @return string The coupon code, or an empty string on failure.
	 */
	public static function create() {
		if ( ! class_exists( 'WC_Coupon' ) ) {
			return '';
		}

		$opts   = WDGames_Settings::get();
		$code   = 'WDG-' . strtoupper( wp_generate_password( 8, false, false ) );
		$coupon = new WC_Coupon();

		$coupon->set_code( $code );
		$coupon->set_discount_type( $opts['discount_type'] );
		$coupon->set_amount( $opts['amount'] );
		$coupon->set_individual_use( true );
		$coupon->set_usage_limit( 1 );
		$coupon->set_usage_limit_per_user( 1 );
		$coupon->set_description( __( 'Generated by a Discount Games mini game.', 'woo-discount-games' ) );

		if ( ! empty( $opts['product_ids'] ) ) {
			$coupon->set_product_ids( $opts['product_ids'] );
		}
		if ( $opts['expiry_days'] > 0 ) {
			$coupon->set_date_expires( time() + ( $opts['expiry_days'] * DAY_IN_SECONDS ) );
		}

		$coupon->update_meta_data( '_wdgames_generated', 'yes' );
		$coupon->save();

		return $coupon->get_id() ? $code : '';
	}
}

